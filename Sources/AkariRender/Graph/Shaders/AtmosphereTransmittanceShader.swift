import AkariCore

extension Akari.RenderGraph
{
  /// drawn by the `atmosphere transmittance` pass.
  struct AtmosphereTransmittanceShader: FullscreenShader
  {
    let name = "atmosphere-transmittance"

    var uniforms: [Declaration]
    {
      Uniforms.atmosphere
      Uniforms.atmosRayleigh
      Uniforms.atmosMie
      Uniforms.atmosMieExtra
      Uniforms.atmosOzone
      Uniforms.atmosGround
    }

    let fragmentGLSL = #"""
      \#(ShaderLibrary.atmosphereGLSL)
      void main()
      {
        Atmosphere a = makeAtmosphere(u_atmosphere, u_atmosRayleigh, u_atmosMie, u_atmosMieExtra, u_atmosOzone, u_atmosGround);
        vec2 uv = gl_FragCoord.xy / vec2(256.0, 64.0);
        vec2 rmu = atmosphereTransmittanceParams(a, uv);
        o_atmosTransmittance_texture = vec4(exp(-atmosphereOpticalDepth(a, rmu.x, rmu.y)), 1.0);
      }
      """#

    let fragmentMSL = #"""
      \#(ShaderLibrary.atmosphereMSL)

      //@main
      {
        Atmosphere a = makeAtmosphere(u_atmosphere, u_atmosRayleigh, u_atmosMie, u_atmosMieExtra, u_atmosOzone, u_atmosGround);
        float2 uv = gl_FragCoord.xy / float2(256.0, 64.0);
        float2 rmu = atmosphereTransmittanceParams(a, uv);
        o_atmosTransmittance_texture = float4(exp(-atmosphereOpticalDepth(a, rmu.x, rmu.y)), 1.0);
      }
      """#
  }
}
